// B-1178: a Codex leg on a non-OpenAI catalog offer — the credential verdict (AC4/AC5), the argv flag on exec
// AND exec resume (AC3), the provider config block — and the OpenAI path pinned byte-identical to the
// pre-B-1178 adapter (AC2). The literals below were captured from origin/main b69f5a0's adapter.

import { describe, it, expect } from 'vitest';
import { HARMONY_MCP_CONNECTION } from './contract.js';
import { runConformance } from './conformance.js';
import {
  CODEX_AUTH_FILE_ENV,
  CODEX_PROVIDER_ENV,
  codexAdapter as A,
  renderCodexConfig,
  resolveCodexCredential,
} from './codex.js';
import { lookupCodexProvider, type CodexProvider } from './codex-providers.js';
import { deriveCostRegime } from './credentials.js';

const OPENROUTER = (() => {
  const r = lookupCodexProvider('openrouter');
  if (!r.ok) throw new Error(r.error);
  return r.provider as CodexProvider;
})();

const PRE_B1178_CONFIG =
  '# Generated by `harmony agent render` (B-1076) from the canonical MCP connection. Do not edit.\n# approval_policy never: an unattended worker must never wait on an approval UI.\napproval_policy = "never"\n# The aggregated AGENTS.md is larger than Codex\'s 32 KiB default, which TRUNCATES silently.\nproject_doc_max_bytes = 262144\n\n[mcp_servers.harmony]\ncommand = "node"\nargs = ["/p/dist/index.js"]\n# required: a worker without Harmony tools must fail BEFORE doing repository work.\nrequired = true\nstartup_timeout_sec = 60\ntool_timeout_sec = 600\ndefault_tools_approval_mode = "auto"\nenv_vars = ["HARMONY_API_TOKEN", "HARMONY_SUPABASE_URL", "HARMONY_SUPABASE_ANON_KEY", "HARMONY_LEG", "HARMONY_CONDUCTION_ID", "HARMONY_MODEL", "HARMONY_PLUGIN_POSTURE", "HARMONY_RUN_CONFIG_JSON", "HARMONY_RUN_CONFIG_PATH", "HARMONY_WEB_ROOT", "HARMONY_DEPLOYMENT_CONFIG", "HARMONY_CONFIG_DIR"]\n';
const PRE_B1178_COLD = ['exec', '--json', '--cd', '/w', '--add-dir', '/w/plugin', '--dangerously-bypass-approvals-and-sandbox', '--dangerously-bypass-hook-trust', '-m', 'gpt-6.1-sol', 'P'];
const PRE_B1178_RESUME = ['exec', 'resume', 't-1', '--json', '--dangerously-bypass-approvals-and-sandbox', '--dangerously-bypass-hook-trust', '-m', 'gpt-6.1-sol', 'P'];

const LOGIN = { [CODEX_AUTH_FILE_ENV]: '/home/worker/.codex-auth-src/auth.json' };
const KEY = { OPENROUTER_API_KEY: 'sk-or-secret-value-123' };

describe('AC2: an OpenAI offer launches byte-identical to before B-1178', () => {
  it('config.toml: no provider, a null provider, and a context window with no provider all render the pre-B-1178 bytes', () => {
    expect(renderCodexConfig(HARMONY_MCP_CONNECTION, { pluginRoot: '/p' }).content).toBe(PRE_B1178_CONFIG);
    expect(renderCodexConfig(HARMONY_MCP_CONNECTION, { pluginRoot: '/p', provider: null, contextWindowTokens: 400000 }).content).toBe(PRE_B1178_CONFIG);
  });
  it('argv: no provider and provider "openai" both build the pre-B-1178 exec and exec-resume argv', () => {
    for (const modelProvider of [undefined, 'openai', '']) {
      expect(A.headless.buildArgv({ pluginDir: '/w/plugin', prompt: 'P', model: 'gpt-6.1-sol', modelProvider })).toEqual(PRE_B1178_COLD);
      expect(A.headless.buildArgv({ pluginDir: '/w/plugin', prompt: 'P', model: 'gpt-6.1-sol', resumeSessionId: 't-1', modelProvider })).toEqual(PRE_B1178_RESUME);
    }
  });
  it('credential: the login cache resolves exactly as before, also explicitly as provider openai', () => {
    expect(resolveCodexCredential(LOGIN)).toEqual({ ok: true, credential: 'login-cache' });
    expect(resolveCodexCredential(LOGIN, 'openai')).toEqual({ ok: true, credential: 'login-cache' });
  });
  it('an OpenAI leg told it is openai ignores a provider key the job binds for every leg (Cloud Run)', () => {
    expect(resolveCodexCredential({ ...LOGIN, ...KEY, [CODEX_PROVIDER_ENV]: 'openai' })).toEqual({ ok: true, credential: 'login-cache' });
    expect(resolveCodexCredential({ ...LOGIN, ...KEY }, 'openai')).toEqual({ ok: true, credential: 'login-cache' });
  });
});

describe('AC3: -c model_provider=<name> rides BOTH exec and exec resume', () => {
  it('cold start: beside -m, before upstream flags, prompt last', () => {
    const argv = A.headless.buildArgv({ pluginDir: '/w/plugin', prompt: 'P', model: 'or/model', modelProvider: 'openrouter', extraFlags: ['--x'] });
    expect(argv).toEqual([...PRE_B1178_COLD.slice(0, 8), '-m', 'or/model', '-c', 'model_provider=openrouter', '--x', 'P']);
  });
  it('resume (the in-place switch path): the same flag, so the switched model stays on the provider', () => {
    const argv = A.headless.buildArgv({ pluginDir: '/w/plugin', prompt: 'P', model: 'or/other', modelProvider: 'openrouter', resumeSessionId: 't-1' });
    expect(argv).toEqual([...PRE_B1178_RESUME.slice(0, 6), '-m', 'or/other', '-c', 'model_provider=openrouter', 'P']);
  });
  it('never a profile: no --profile flag and no [profiles.*] table', () => {
    const argv = A.headless.buildArgv({ pluginDir: '/w/plugin', prompt: 'P', modelProvider: 'openrouter' });
    expect(argv).not.toContain('--profile');
    expect(renderCodexConfig(HARMONY_MCP_CONNECTION, { provider: OPENROUTER }).content).not.toContain('[profiles');
  });
  it('refuses a provider name that is not a bare TOML key', () => {
    expect(() => A.headless.buildArgv({ pluginDir: '/w/plugin', prompt: 'P', modelProvider: 'x y=1' })).toThrow(/invalid model provider/);
  });
});

describe('the provider config block', () => {
  it('appends [model_providers.openrouter] with name, base_url, env_key and wire_api; the key value never appears', () => {
    const c = renderCodexConfig(HARMONY_MCP_CONNECTION, { pluginRoot: '/p', provider: OPENROUTER }).content;
    expect(c.startsWith(PRE_B1178_CONFIG)).toBe(true);
    expect(c.slice(PRE_B1178_CONFIG.length)).toBe(
      '\n# B-1178: the OpenRouter provider; the key is read from OPENROUTER_API_KEY (secret harmony-provider-openrouter-key).\n' +
        '[model_providers.openrouter]\nname = "OpenRouter"\nbase_url = "https://openrouter.ai/api/v1"\nenv_key = "OPENROUTER_API_KEY"\nwire_api = "responses"\n',
    );
    expect(c).not.toContain('model_context_window');
  });
  it('writes model_context_window as a ROOT key (before every table) when the catalog knows it', () => {
    const c = renderCodexConfig(HARMONY_MCP_CONNECTION, { pluginRoot: '/p', provider: OPENROUTER, contextWindowTokens: 262144 }).content;
    const at = c.indexOf('model_context_window = 262144\n');
    expect(at).toBeGreaterThan(0);
    expect(at).toBeLessThan(c.indexOf('[mcp_servers.harmony]'));
  });
  it('omits model_context_window for a null / non-positive / non-integer window', () => {
    for (const w of [null, 0, -1, 1.5]) {
      expect(renderCodexConfig(HARMONY_MCP_CONNECTION, { provider: OPENROUTER, contextWindowTokens: w }).content).not.toContain('model_context_window');
    }
  });
});

describe('the provider credential (B-934 discipline, names only)', () => {
  it('a provider leg resolves to api-key, which derives metered', () => {
    expect(resolveCodexCredential(KEY, 'openrouter')).toEqual({ ok: true, credential: 'api-key' });
    expect(resolveCodexCredential({ ...KEY, [CODEX_PROVIDER_ENV]: 'openrouter' })).toEqual({ ok: true, credential: 'api-key' });
    expect(resolveCodexCredential(KEY)).toEqual({ ok: true, credential: 'api-key' });
    expect(deriveCostRegime('api-key')).toBe('metered');
  });
  it('AC4: the provider key not mounted refuses, naming the secret harmony-provider-<name>-key', () => {
    const r = resolveCodexCredential({}, 'openrouter');
    expect(r.ok).toBe(false);
    if (!r.ok) {
      expect(r.error).toContain('harmony-provider-openrouter-key');
      expect(r.error).toContain('OPENROUTER_API_KEY');
    }
    expect(resolveCodexCredential({ OPENROUTER_API_KEY: '' }, 'openrouter').ok).toBe(false);
  });
  it.each([CODEX_AUTH_FILE_ENV, 'OPENAI_API_KEY', 'CODEX_API_KEY'])(
    'AC5: %s beside the provider key is a config error — named, value never echoed',
    (name) => {
      const r = resolveCodexCredential({ ...KEY, [name]: 'secret-value-xyz' }, 'openrouter');
      expect(r.ok).toBe(false);
      if (!r.ok) {
        expect(r.error).toContain(name);
        expect(r.error).not.toContain('secret-value-xyz');
        expect(r.error).not.toContain('sk-or-secret-value-123');
      }
    },
  );
  it('AC5 with no provider named: the login cache and a provider key together are refused, not preferred', () => {
    const r = A.auth.resolveCredential({ ...LOGIN, ...KEY });
    expect(r.ok).toBe(false);
    if (!r.ok) {
      expect(r.error).toContain(CODEX_AUTH_FILE_ENV);
      expect(r.error).toContain('OPENROUTER_API_KEY');
      expect(r.error).not.toContain('sk-or-secret-value-123');
    }
  });
  it('two provider keys and no provider named: refused rather than picking one', () => {
    expect(resolveCodexCredential({ ...KEY, DEEPSEEK_API_KEY: 'k' }).ok).toBe(false);
  });
  it('a named provider ignores another provider key bound beside it', () => {
    expect(resolveCodexCredential({ ...KEY, DEEPSEEK_API_KEY: 'k' }, 'openrouter')).toEqual({ ok: true, credential: 'api-key' });
  });
  it('an unknown provider is refused by name', () => {
    const r = resolveCodexCredential(KEY, 'nope');
    expect(r).toMatchObject({ ok: false });
    if (!r.ok) expect(r.error).toContain("'nope'");
  });
});

describe('adapter seams after B-1178', () => {
  it('accepts login-cache and api-key; the api-key row names a registry key var; still conformant', () => {
    expect(A.auth.acceptedCredentials).toEqual(['login-cache', 'api-key']);
    expect(A.auth.credentialEnv['api-key']).toBe('OPENROUTER_API_KEY');
    expect(runConformance(A).filter((r) => !r.pass)).toEqual([]);
  });
  it('every registry key var is a standing secret, never in the forwarded per-leg allowlist', () => {
    expect(A.env.standingSecrets).toEqual(expect.arrayContaining(['OPENROUTER_API_KEY', 'DEEPSEEK_API_KEY']));
    for (const k of ['OPENROUTER_API_KEY', 'DEEPSEEK_API_KEY', CODEX_PROVIDER_ENV]) expect(A.env.allowlist).not.toContain(k);
  });
  it('telemetry reports the metered regime for an api-key leg (derived, never chosen)', () => {
    const rec = A.telemetry.parse(A.telemetry.sampleOutput, { model: 'or/model', credential: 'api-key' });
    expect(rec).toMatchObject({ credential: 'api-key', costRegime: 'metered' });
  });
});
